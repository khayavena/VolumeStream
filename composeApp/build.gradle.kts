    picked = ios_devices[0]

if picked is None:
    sys.stderr.write("No available iOS simulators found.\n")
    sys.exit(2)

print(picked["udid"])
PY
            )"

            if [[ -z "${'$'}SIMULATOR_UDID" ]]; then
                echo "Failed to resolve an iOS simulator UDID." >&2
                exit 2
