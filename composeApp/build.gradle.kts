fun projectEnvOrDefault(name: String, defaultValue: String): String =
    System.getenv(name)?.takeIf { it.isNotBlank() } ?: defaultValue

fun adbExecutableName(): String = if (System.getProperty("os.name").lowercase().contains("win")) "adb.exe" else "adb"

fun resolveAdbExecutable(): String {
    val adbOverride = System.getenv("ADB")?.trim().orEmpty()
    if (adbOverride.isNotEmpty()) return adbOverride

    val adbName = adbExecutableName()
    val candidates = mutableListOf<String>()

    fun addSdkCandidate(sdkRoot: String?) {
        val root = sdkRoot?.trim().orEmpty()
        if (root.isEmpty()) return
        candidates += "$root/platform-tools/$adbName"
    }

    addSdkCandidate(System.getenv("ANDROID_SDK_ROOT"))
    addSdkCandidate(System.getenv("ANDROID_HOME"))
    addSdkCandidate(localProps.getProperty("sdk.dir"))

    val found = candidates.firstOrNull { file(it).exists() }
    if (found != null) return found

    // Fall back to PATH-based resolution for environments where adb is globally available.
    return adbName
}

fun adbTargetArgs(): List<String> {
    val serial = System.getenv("ANDROID_SERIAL")?.trim().orEmpty()
    return if (serial.isNotEmpty()) listOf("-s", serial) else emptyList()
}

data class AdbDevice(val serial: String, val state: String) {
    val isEmulator: Boolean get() = serial.startsWith("emulator-")
}

fun listAdbDevices(adb: String): List<AdbDevice> {
    val out = ByteArrayOutputStream()
    exec {
        commandLine(adb, "devices")
        standardOutput = out
    }
    val devicesText = out.toString().trim()
    return devicesText
        .lineSequence()
        .drop(1)
        .map { it.trim() }
        .filter { it.isNotEmpty() && it.contains("\t") }
        .map { line ->
            val parts = line.split(Regex("\\s+"))
            AdbDevice(serial = parts[0], state = parts.getOrElse(1) { "unknown" })
        }
        .toList()
}

fun resolveAdbTargetArgs(adb: String, preferEmulator: Boolean): List<String> {
    val configuredSerial = System.getenv("ANDROID_SERIAL")?.trim().orEmpty()
    val devices = listAdbDevices(adb)
    val onlineDevices = devices.filter { it.state == "device" }

    if (configuredSerial.isNotEmpty()) {
        val matched = devices.firstOrNull { it.serial == configuredSerial }
        if (matched == null) {
            val known = devices.joinToString { "${it.serial}(${it.state})" }
            throw GradleException("ANDROID_SERIAL '$configuredSerial' not found in adb devices. Known: ${if (known.isBlank()) "none" else known}")
        }
        if (matched.state != "device") {
            throw GradleException("ANDROID_SERIAL '$configuredSerial' is '${matched.state}'. Ensure it is online/authorized, then re-run.")
        }
        return listOf("-s", configuredSerial)
    }

    if (onlineDevices.isEmpty()) {
        throw GradleException(
            "No Android device/emulator found for adb. Start a device in Android Studio Device Manager (or connect a physical device) and re-run."
        )
    }

    if (onlineDevices.size == 1) {
        return listOf("-s", onlineDevices.first().serial)
    }

    if (preferEmulator) {
        val emulators = onlineDevices.filter { it.isEmulator }
        if (emulators.size == 1) {
            return listOf("-s", emulators.first().serial)
        }
    }

    val choices = onlineDevices.joinToString { it.serial }
    throw GradleException("Multiple adb targets are online: $choices. Set ANDROID_SERIAL to choose one.")
}

tasks.register("launchPhoneDebugFromIde") {
    group = "ide"
    description = "Assemble, install, and launch the Android phone debug app (uses ANDROID_SERIAL when set)."
    dependsOn("assemblePhoneDebug")
    doLast {
        val adb = resolveAdbExecutable()
        val targetArgs = resolveAdbTargetArgs(adb, preferEmulator = false)
        val apk = layout.buildDirectory.file("outputs/apk/phone/debug/composeApp-phone-debug.apk").get().asFile
        if (!apk.exists()) {
            throw GradleException("Phone APK not found: ${apk.absolutePath}")
        }
        exec {
            commandLine(listOf(adb) + targetArgs + listOf("install", "-r", apk.absolutePath))
        }
        exec {
            commandLine(
                listOf(adb) + targetArgs + listOf(
                    "shell", "am", "start", "-W", "-n",
                    "com.vdigital.volumestream.phone/com.vdigital.volumestream.platform.activity.MainActivity"
                )
            )
        }
    }
}

